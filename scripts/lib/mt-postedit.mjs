// Пост-редактирование машинного перевода (Yandex Translate) инструкций.
// Правила безопасные: типографика и терминология, без перестройки фраз.

const TERM_FIXES = [
  // типовые артефакты MT в фитнес-тексте
  [/\bмашина Смита\b/gi, 'тренажёр Смитта'],
  [/\bмашине Смита\b/gi, 'тренажёре Смитта'],
  [/\bмашину Смита\b/gi, 'тренажёр Смитта'],
  [/тренажер Смита/gi, 'тренажёр Смитта'],
  [/тренажер Smith/gi, 'тренажёр Смитта'],
  [/тренажере Smith/gi, 'тренажёре Смитта'],
  [/\bтренажер smith\b/gi, 'тренажёр Смитта'],
  [/\bмяч Bosu\b/gi, 'платформа Босу'],
  [/\bмяче Bosu\b/gi, 'платформе Босу'],
  [/\bBosu\b/gi, 'Босу'],
  [/гриф EZ[ -]?Curl/gi, 'EZ-гриф'],
  [/гриф EZ[ -]?bour/gi, 'EZ-гриф'],
  [/\bEZ-?bour\b/gi, 'EZ-гриф'],
  [/\bEZ Curl\b/gi, 'EZ-гриф'],
  [/\bT-bar Row\b/gi, 'Т-гриф'],
  [/\bT-bar\b/gi, 'Т-гриф'],
  [/станок для завивки волос Preacher/gi, 'скамья Скотта'],
  [/станке для завивки волос Preacher/gi, 'скамье Скотта'],
  [/\bSmith\b/g, 'Смитт'],
  [/\bbosu\b/g, 'босу'],
];

// конвертация футов в метры (округление до 0,1)
function feetToMeters(m) {
  const v = Math.round(m * 0.3048 * 10) / 10;
  return String(v).replace('.', ',');
}

export function postEdit(s) {
  let t = String(s);

  // нормализация пробелов
  t = t.replace(/\u00a0/g, ' ').replace(/\s+/g, ' ').trim();
  if (!t) return t;

  // ASCII-кавычки → «ёлочки» (только короткие пары)
  t = t.replace(/"([^"]{1,100})"/g, '«$1»');

  // дефис/короткое тире между пробелами → длинное тире
  t = t.replace(/\s+[–-]\s+/g, ' — ');

  // Tip / Совет:
  t = t.replace(/\b(Tips|Tip|Советы|Совет)\s*:/gi, 'Совет:');

  // пробел перед знаком препинания
  t = t.replace(/\s+([.,;:!?])/g, '$1');

  // футы → метры (в т.ч. диапазоны «2-3 футов»)
  t = t.replace(/нескольких футах/gi, 'в метре');
  t = t.replace(/нескольких футов/gi, 'около метра');
  t = t.replace(
    /(\d+)(?:\s*[-–]\s*(\d+))?\s*фут(?:а|ов|е)?\b/gi,
    (all, a, b) => {
      if (b) return `${feetToMeters(Number(a))}–${feetToMeters(Number(b))} м`;
      return `${feetToMeters(Number(a))} м`;
    }
  );

  // терминология
  for (const [re, to] of TERM_FIXES) t = t.replace(re, to);

  // первая буква заглавная
  t = t[0].toUpperCase() + t.slice(1);

  // финальная точка, если предложение её не имеет
  if (/[а-яёa-z0-9)]$/i.test(t)) t += '.';

  return t;
}
